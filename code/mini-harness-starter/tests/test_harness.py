import json

from mini_harness.harness import Budget, Harness, parse_reply
from mini_harness.tools import TOOLS


class ScriptedModel:
    """Returns pre-written replies in order and records what it was shown."""

    def __init__(self, replies):
        self.replies = list(replies)
        self.seen = []

    def __call__(self, messages):
        self.seen.append(messages)
        return self.replies.pop(0) if self.replies else json.dumps({"final": "out of script"})


def call(tool, **args):
    return json.dumps({"tool": tool, "args": args})


def make_repo(tmp_path):
    (tmp_path / "src").mkdir()
    (tmp_path / "src" / "a.py").write_text("print('a')\n")
    (tmp_path / "AGENTS.md").write_text("Run tests with pytest.\n")
    (tmp_path / ".env").write_text("SECRET=hunter2\n")
    return tmp_path


def test_three_tools_registered_with_schemas():
    assert {"read_file", "list_dir", "run_tests"} <= set(TOOLS)
    for t in TOOLS.values():
        assert t.description and isinstance(t.params, dict)


def test_final_answer_stops_the_loop(tmp_path):
    res = Harness(ScriptedModel([json.dumps({"final": "done"})]), make_repo(tmp_path)).run("hi")
    assert res.answer == "done" and res.stop_reason == "final answer" and res.turns == 1


def test_tool_result_is_fed_back_to_the_model(tmp_path):
    model = ScriptedModel([call("list_dir", path="src"), json.dumps({"final": "one file"})])
    res = Harness(model, make_repo(tmp_path)).run("what is in src?")
    second_view = model.seen[1]
    assert any("a.py" in m["content"] for m in second_view)
    assert res.answer == "one file"


def test_agents_md_is_in_the_context(tmp_path):
    model = ScriptedModel([json.dumps({"final": "ok"})])
    Harness(model, make_repo(tmp_path)).run("hi")
    assert "Run tests with pytest." in model.seen[0][0]["content"]


def test_turn_limit_stops_a_runaway_model(tmp_path):
    model = ScriptedModel([call("list_dir", path=".")] * 50)
    res = Harness(model, make_repo(tmp_path), budget=Budget(max_turns=3)).run("loop forever")
    assert res.answer is None and "turn limit" in res.stop_reason and res.turns == 3


def test_token_budget_stops_the_loop(tmp_path):
    model = ScriptedModel([call("read_file", path="src/a.py")] * 50)
    res = Harness(model, make_repo(tmp_path), budget=Budget(max_turns=100, max_tokens=300)).run("go")
    assert res.answer is None and "token" in res.stop_reason


def test_paths_cannot_escape_the_repo(tmp_path):
    model = ScriptedModel([call("read_file", path="../../etc/passwd"), json.dumps({"final": "x"})])
    Harness(model, make_repo(tmp_path)).run("read it")
    assert "outside" in model.seen[1][-1]["content"].lower()


def test_secret_files_are_not_readable(tmp_path):
    model = ScriptedModel([call("read_file", path=".env"), json.dumps({"final": "x"})])
    Harness(model, make_repo(tmp_path)).run("read the env")
    assert "hunter2" not in model.seen[1][-1]["content"]


def test_run_tests_needs_human_approval(tmp_path):
    model = ScriptedModel([call("run_tests", target="."), json.dumps({"final": "x"})])
    Harness(model, make_repo(tmp_path), approve=lambda name, args: False).run("run tests")
    assert "denied" in model.seen[1][-1]["content"].lower()


def test_unknown_tool_is_reported_not_crashed(tmp_path):
    model = ScriptedModel([call("delete_everything"), json.dumps({"final": "x"})])
    res = Harness(model, make_repo(tmp_path)).run("go")
    assert "unknown tool" in model.seen[1][-1]["content"].lower() and res.answer == "x"


def test_parse_reply_finds_json_inside_prose():
    assert parse_reply('Sure! ```json\n{"tool": "list_dir", "args": {"path": "."}}\n```')["tool"] == "list_dir"
    assert parse_reply("I think we are done here.")["final"]
